#!/bin/bash

CORES=$(nproc)
# nproc - выводит количество доступных логических ядер процессора

HALF_CORES=$(( CORES / 2 ))
# $(( ... )) - арифметика
# CORES / 2 - целочисленное деление и результат запишется в HALF_CORES

for (( i=0; i<HALF_CORES; i++ )); do
    taskset -c $i bash -c 'while true; do :; done' & 
    # taskset - улилита которая привязывает процесс к определенному ядру CPU
    # -c $i - указание конкретного ядра
    # bash -c '...' - запускает новый экземпляр bash и передает ему команду в кавычках
    # 'while true; do :; done' - бесконечный цикл - заставляет процессор работать на 100 процентов
    # & - запускает процесс в фоне чтобы цикл не остановился на первой же итерации и пошел дальше

    echo "запущен процесс загрузки CPU на ядре $1 с PID: $!"
    # $! - PID последнего процесса запущенного в фоне
    # PID - уникальный числовой номер который операционная система присваевает каждому запущенному процессу для управления им
done