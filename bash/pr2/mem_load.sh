#!/bin/bash

head -c 128M /dev/zero | tail &
# head -c 128M /dev/zero - читает из /dev/zero ровно 128 мегабайт нулей и отдает из в стандартный вывод  
# | - передает вывод первый команды на вход второй
# tail - выводит 10 строк но tail без файлов читает stdin
# пока head выдает данные, tail держит эти данные в буфере

echo "апущен процесс связанный с памятью -> PID: $!"
# выводит PID последнего фонового процесса (группы процессов head | tail в данном случае)