#!/bin/bash

dd if=/dev/zero of=./temp_file bs=1M count=1
# dd - копирование данных блоками
# if=/dev/zero - источник - бесконечный поток нулей
# of=./temp_file - приемник - создание файла temp_file в текущей папке
# bs=1M - размер блока 1 мб
# count=1 - количество блоков = 1 - в итоге создаеться файл ровно на 1 мб

while true; do
    dd if=/dev/zero of=./temp_file bs=1M count=1 conv=notrunc,fdatasync &
    # тот же dd но с дополнительными ключами
    # conv=notrunc - не обрязать файл перед записью (перезаписывание)
    # conc=fdatasync - принудительное сбрасывание данных с физической записью на диск после каждой операции
    # & - запуск в фоне

    echo "запущен процесс dd -> PID: $!"
    wait $!
    # wait - заставляет текущий скрипт подождать пока дочерний процесс с указанным PID не завершиться
    # $! — PID только что запущенного dd
done