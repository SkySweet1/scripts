/*
Задача 6. «Тест на раскрутку стека (RAII)»
Создай класс Resource с конструктором и деструктором. В конструкторе выведи "Ресурс захвачен", в деструкторе — "Ресурс освобожден".
В функции main открой блок try. Внутри создай локальный объект Resource. Сразу после его создания сгенерируй любое исключение (throw 42;). Добавь блок catch для int.
Вопрос: В каком порядке будут выведены сообщения в консоль? Почему деструктор сработал, ведь до конца функции дело не дошло?
(Подсказка из текста: Раздел 1.3. Это сердце твоей курсовой — идиома RAII).
*/
#include <iostream>

class Resourse
{
public:
    Resourse()
    {
        std::cout << "ресурс захвачен" << '\n';
    }

    ~Resourse()
    {
        std::cout << "ресурс освобожден" << '\n';
    }
};

int main(void)
{
    try
    {
        Resourse res;
        std::cout << "1" << '\n';
        throw 42;
        std::cout << "2" << '\n';
    }
    catch (int code)
    {
        std::cout << "3" << '\n';
        std::cerr << code << '\n';
        std::cout << "4" << '\n';
    }

    /*
        ресурс захвачен
        1
        ресурс освобожден
        3
        42
        4

        программа зашла в try и создала обьекст res
        сработал конструктор
        программа наткнулась на throw 42 и поняла что дальше нельзя выполнять код в try и выпрыгивает из него
        начинаеться раскрутка стека - так как мы выходим из области видимости где жил res - программа обязана его уничтодить
        вызываеться деструктор
        управление попадает в catch
    */

    return 0;
}