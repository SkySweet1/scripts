/*
Задача 17. «Бомба замедленного действия» (Исключение в деструкторе)

Тема: std::terminate при раскрутке стека.
Что делать:

Создай класс Bomb. В его деструкторе ~Bomb() напиши throw std::runtime_error("Взрыв в деструкторе!"); (не забудь пометить деструктор как noexcept(false), иначе компилятор не даст даже скомпилировать).
В main открой блок try.
Внутри try создай объект Bomb b;.
Сразу после создания объекта выброси другое исключение: throw std::logic_error("Ошибка в try");.
Добавь catch (const std::exception& e), который просто выводит "Поймано".
Вопрос: Что произойдет, когда программа запустится? Сработает ли catch в main? Какая функция будет вызвана неявно?
(Подсказка: вспомни, что происходит, когда во время раскрутки стека 
(из-за первого исключения) деструктор выбрасывает второе).
*/
#include <iostream>
#include <stdexcept>

class Bomb
{
public:
    Bomb() {}

    ~Bomb() noexcept(false) {
        throw std::runtime_error("explosion");
    }

    /*
    Что значит noexcept(false)?
        Это означает: «Я (функция) НЕ даю гарантию, что не выброшу исключение. 
        Я оставляю за собой право упасть с ошибкой».

    В современном C++ (начиная с C++11) внутрь скобок можно пихать не только true/false, но и целые проверки.
    Например, можно написать так:
        void myFunc() noexcept(noexcept(otherFunc()));

    Это читается так: "Функция myFunc гарантирует, что не выбросит исключение, 
    если функция otherFunc тоже не выбрасывает исключение". 
    Это используется в шаблонах (метапрограммировании), чтобы компилятор сам вычислял безопасность.
    */
};

