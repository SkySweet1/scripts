/*
Задача 10. «Спецификация noexcept»
Напиши функцию-перемещения (move-конструктор) для любого класса и пометь её как noexcept.
Вопрос: Почему стандартный контейнер std::vector при переполнении
(когда ему нужно перевыделить память) будет использовать ваш move-конструктор,
только если он помечен noexcept? Что произойдет, если он не помечен?
(Подсказка из текста: Раздел 1.4, Спецификация noexcept).
*/
#include <iostream>
#include <utility>

class Class
{
private:
    int *data;

public:
    Class(int value)
    {
        data = new int(value);

        std::cout << "object created" << '\n';
    }

    Class(Class &&other) noexcept
    { // это как раз конктруктор перемещения
        data = other.data;
        other.data = nullptr;
        std::cout << "object moved" << '\n';
    }

    ~Class()
    {
        delete data;
        std::cout << "dstr" << '\n';
    }
};

int main(void)
{
    Class object_1(42);
    Class object_2(std::move(object_1));

    /*
    move - просто забираем указатель а не копируем перетаскиваем и удаляем
    можно подумать что std::move() чтото попируем или перемещает но это не так
    эта функция работает как удостоверение разрешающее у одно обьекта забрать все ресурсы и присвоить их другому обьекту
    если не писать std::move() то компилятор по умолчанию всегда будет пытаться копировать (потомучто так безопаснее, вдруг нам еще нужен будет этот обьект)

    noexcept - это гарантия что функция проверенная и исключения не выброситься абсолютно никогда что бы ни случилось
    это помогает делать более быстрый и оптимизированный код. однако если все же выброситься исключение то программа немедленно вызовет std::terminate

    связь с std::vector
        не был использован std::vector но был написан класс для него
        когда в векторе заканчиваеться памят то он выделяет новую и перекладывает туда старые элементы
        и тут у него есть выбор:
            переместить(move) - быстро
                однако если вылетит исключение, старая память уже опустошена а новая заполнена лись наполовину
                вектор сломан и данные потеряны - катастрофа
            скопировать(copy) - медленно
                но если вылелит исключение, вектор просто удалит новую память и оставит старую целой и невредимой
                вектор как будто откатился назад во времени
        это называеться строгая рагантия безопасности (strong exeption guarantee) - все или ничего

        Как вектор решает, что выбрать?
            Он смотрит на твой Move-конструктор. Если там написано noexcept (ты дал обещание, что перемещение не упадет), вектор говорит: «Отлично, раз ты гарантируешь, что не упадешь, я буду использовать быстрый Move!»
            Если noexcept нет, вектор боится: «А вдруг ты упадешь, и я потеряю данные? Нет уж, я лучше буду медленно копировать, чтобы если что — откатиться».

    noexcept гарантирует, что функция не выбросит исключение.
    Это критически важно для контейнеров (например, std::vector).
    При перевыделении памяти вектор использует move-конструктор только в том случае,
    если он помечен noexcept. В противном случае вектор использует
    копирование для обеспечения строгой гарантии безопасности исключений
    (чтобы при сбое старые данные не были утеряны или испорчены)
    */

    return 0;
}